/**
 * The stock Player's UI actions and the argument each one takes. This mirrors
 * `ui::kPlayerActions` in PrismatiXEngine/Engine/UI/Actions/
 * PlayerActionContract.h, which the Player registers and dispatches from; a
 * test keeps the two in step.
 */
export type PlayerActionArgumentType = "integer" | "boolean" | "string";

export interface PlayerActionSpec {
  /** The TSX `arguments` key and its type; absent when the action takes none. */
  readonly argument?: {readonly key: string; readonly type: PlayerActionArgumentType};
  readonly category: string;
  /** "ui" when GalgameUI runs the action instead of the Player host. */
  readonly owner?: "ui";
}

