import {serializeDocument, validateDocument} from "./contracts.js";
import type {JsonValue, Result} from "./types.js";

interface MotionLayerBase {
  readonly id: string;
  readonly parent?: string;
  readonly z?: number;
  readonly anchorX?: number;
  readonly anchorY?: number;
  readonly x?: number;
  readonly y?: number;
  readonly scaleX?: number;
  readonly scaleY?: number;
  readonly rotation?: number;
  /** Local time = parent-local time × timeScale + timeOffset. Revision 7. */
  readonly timeOffset?: number;
  readonly timeScale?: number;
  readonly opacity?: number;
  readonly visible?: boolean;
}

export interface MotionImageLayer extends MotionLayerBase {
  readonly kind?: "image";
  readonly image: string;
  /** Pixel rectangles within image; frame tracks select an index without
   * loading a new texture on each key. Requires schema revision 2. */
  readonly frames?: readonly MotionFrame[];
  /** Another animated layer whose alpha clips this layer. Mask sources are
   * not painted independently. Requires revision 6. */
  readonly mask?: string;
  /** Normal alpha, additive light, or multiplicative tint. Revision 4. */
  readonly blendMode?: "normal" | "additive" | "multiply";
  readonly width: number;
  readonly height: number;
}

/** Invisible transform/time parent for inlined sub-timelines. Revision 7. */
export interface MotionGroupLayer extends MotionLayerBase {
  readonly kind: "group";
  readonly image?: never;
  readonly frames?: never;
  readonly mask?: never;
  readonly blendMode?: never;
  readonly width?: number;
  readonly height?: number;
}

export type MotionLayer = MotionImageLayer | MotionGroupLayer;

export interface MotionFrame {
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
}

export type MotionProperty = "x" | "y" | "scaleX" | "scaleY" |
  "rotation" | "opacity" | "visible" | "frame";
export type MotionCurve = "step" | "linear" | "easeIn" | "easeOut" |
  "easeInOut" | "cubicBezier";

export interface MotionKey {
  readonly time: number;
  readonly value: number | boolean;
  readonly curve?: MotionCurve;
  /** Normalized timing cubic; required only for cubicBezier keys. */
  readonly bezier?: {readonly x1: number; readonly y1: number;
    readonly x2: number; readonly y2: number};
}

export interface MotionTrack {
  readonly layer: string;
  readonly property: MotionProperty;
  readonly keys: readonly MotionKey[];
}

export interface MotionAudioMarkerInput {
  /** Optional author-facing identity; autogenerated when omitted. */
  readonly id?: string;
  readonly time: number;
  readonly audio: string;
  readonly bus: "se" | "voice";
}

export interface MotionAudioMarker extends MotionAudioMarkerInput {
  readonly id: string;
}

export interface MotionInput {
  readonly id: string;
  readonly canvas: {readonly width: number; readonly height: number};
  readonly duration: number;
  readonly loop?: boolean;
  readonly scaleMode?: "fit" | "fill" | "stretch";
  readonly layers: readonly MotionLayer[];
  readonly tracks?: readonly MotionTrack[];
  /** Sound fired when ordinary playback crosses this point, never by Seek. */
  readonly markers?: readonly MotionAudioMarkerInput[];
}

export interface MotionDocument extends MotionInput {
  readonly format: "PrismatiXMotion";
  readonly schemaRevision: 1 | 2 | 3 | 4 | 5 | 6 | 7;
  readonly loop: boolean;
  readonly tracks: readonly MotionTrack[];
  readonly markers?: readonly MotionAudioMarker[];
}

/** Author a deterministic image-layer .pxmotion clip. Atlas frames use
 * revision 2, audio markers revision 3, blend modes revision 4, and cubic
 * timing curves revision 5, layer alpha masks revision 6, and local-time
 * transform groups revision 7.
 * Blur and nested motion remain unsupported. */
export function defineMotion(input: MotionInput): Result<MotionDocument> {
  const atlas = input.layers.some((layer) => layer.frames !== undefined) ||
    input.tracks?.some((track) => track.property === "frame") === true;
  const hasMarkers = (input.markers?.length ?? 0) > 0;
  const hasBlendModes = input.layers.some((layer) => layer.blendMode !== undefined);
  const hasBezier = input.tracks?.some((track) => track.keys.some((key) =>
    key.curve === "cubicBezier" || key.bezier !== undefined)) === true;
  const hasMasks = input.layers.some((layer) => layer.mask !== undefined);
  const hasLocalTime = input.layers.some((layer) => layer.kind === "group" ||
    layer.timeOffset !== undefined || layer.timeScale !== undefined);
  const usedMarkerIds = new Set(input.markers?.flatMap((marker) =>
    marker.id === undefined ? [] : [marker.id]) ?? []);
  const markers = input.markers?.map((marker, index) => {
    if (marker.id !== undefined) return {...marker, id: marker.id};
    const base = `marker-${index + 1}`;
    let id = base;
    for (let suffix = 2; usedMarkerIds.has(id); suffix++) id = `${base}-${suffix}`;
    usedMarkerIds.add(id);
    return {...marker, id};
  });
  const document: MotionDocument = {
    format: "PrismatiXMotion",
    schemaRevision: hasLocalTime ? 7 : hasMasks ? 6 : hasBezier ? 5 : hasBlendModes ? 4 :
      hasMarkers ? 3 : atlas ? 2 : 1,
    id: input.id,
    canvas: input.canvas,
    duration: input.duration,
    loop: input.loop ?? false,
    scaleMode: input.scaleMode ?? "fit",
    layers: input.layers.map((layer): MotionLayer => {
      const common = {
        id: layer.id,
        ...(layer.parent === undefined ? {} : {parent: layer.parent}),
        z: layer.z ?? 0,
        anchorX: layer.anchorX ?? 0,
        anchorY: layer.anchorY ?? 0,
        x: layer.x ?? 0,
        y: layer.y ?? 0,
        scaleX: layer.scaleX ?? 1,
        scaleY: layer.scaleY ?? 1,
        rotation: layer.rotation ?? 0,
        ...(layer.timeOffset === undefined ? {} : {timeOffset: layer.timeOffset}),
        ...(layer.timeScale === undefined ? {} : {timeScale: layer.timeScale}),
        opacity: layer.opacity ?? 1,
        visible: layer.visible ?? true,
      };
      if (layer.kind === "group") return {
        ...common, kind: "group", width: layer.width ?? 0,
        height: layer.height ?? 0,
      };
      return {
        ...common, image: layer.image,
        ...(layer.frames === undefined ? {} :
          {frames: layer.frames.map((frame) => ({...frame}))}),
        ...(layer.mask === undefined ? {} : {mask: layer.mask}),
        ...(layer.blendMode === undefined ? {} : {blendMode: layer.blendMode}),
        width: layer.width, height: layer.height,
      };
    }),
    tracks: (input.tracks ?? []).map((track) => ({
      layer: track.layer,
      property: track.property,
      keys: track.keys.map((key) => ({
        time: key.time,
        value: key.value,
        curve: key.curve ?? (track.property === "visible" || track.property === "frame"
          ? "step" : "linear"),
        ...(key.bezier === undefined ? {} : {bezier: {...key.bezier}}),
      })),
    })),
    ...(hasMarkers ? {markers: markers!} : {}),
  };
  return validateDocument<MotionDocument>("motion", document);
}

export function serializeMotion(input: MotionInput): Result<string> {
  const defined = defineMotion(input);
  if (!defined.valid || defined.value === undefined)
    return {diagnostics: defined.diagnostics, valid: false};
  return serializeDocument("motion", defined.value as unknown as JsonValue);
}

export interface InlineMotionOptions {
  /** Group ID and prefix for every inlined layer and marker ID. */
  readonly id: string;
  /** Parent layer in the destination clip, if any. */
  readonly parent?: string;
  /** Start position in the parent's local seconds; hidden before this point. */
  readonly at?: number;
  /** Child playback speed relative to the parent's local clock. */
  readonly speed?: number;
  /** Offset applied to the child's draw-layer z values. */
  readonly z?: number;
  readonly x?: number;
  readonly y?: number;
  readonly scaleX?: number;
  readonly scaleY?: number;
  readonly rotation?: number;
  readonly opacity?: number;
  /** false keeps the entire inserted clip hidden; otherwise appears at `at`. */
  readonly visible?: boolean;
}

/** Inline one non-looping motion under a revision-7 transform/time group.
 * Child IDs, mask references, tracks and audio markers are rebased together.
 * The child canvas remains in its authored logical units; use scaleX/scaleY
 * when placing it in a differently sized parent canvas. The group becomes
 * visible at its local time zero and holds its final pose after it ends. */
export function inlineMotion(outer: MotionInput, child: MotionInput,
  options: InlineMotionOptions): Result<MotionDocument> {
  const error = (code: string, message: string): Result<MotionDocument> => ({
    valid: false, diagnostics: [{severity: "error", code, message}],
  });
  const base = defineMotion(outer);
  if (!base.valid || base.value === undefined) return base;
  const nested = defineMotion(child);
  if (!nested.valid || nested.value === undefined) return nested;
  if (nested.value.loop) return error("PXMOTION2001",
    "A looping child clip cannot be inlined because local group time does not repeat");
  const at = options.at ?? 0;
  const speed = options.speed ?? 1;
  if (!Number.isFinite(at) || at < 0 || !Number.isFinite(speed) || speed <= 0)
    return error("PXMOTION2002", "Inline motion requires at >= 0 and speed > 0");
  const layerId = (id: string) => `${options.id}-${id}`;
  const group: MotionGroupLayer = {
    id: options.id, kind: "group",
    ...(options.parent === undefined ? {} : {parent: options.parent}),
    timeOffset: -at * speed, timeScale: speed,
    ...(options.x === undefined ? {} : {x: options.x}),
    ...(options.y === undefined ? {} : {y: options.y}),
    ...(options.scaleX === undefined ? {} : {scaleX: options.scaleX}),
    ...(options.scaleY === undefined ? {} : {scaleY: options.scaleY}),
    ...(options.rotation === undefined ? {} : {rotation: options.rotation}),
    ...(options.opacity === undefined ? {} : {opacity: options.opacity}),
    visible: false,
  };
  const layers: MotionLayer[] = nested.value.layers.map((layer): MotionLayer => {
    if (layer.kind === "group") return {
      ...layer,
      id: layerId(layer.id),
      parent: layer.parent === undefined ? options.id : layerId(layer.parent),
      z: (layer.z ?? 0) + (options.z ?? 0),
    };
    return {
      ...layer,
      id: layerId(layer.id),
      parent: layer.parent === undefined ? options.id : layerId(layer.parent),
      z: (layer.z ?? 0) + (options.z ?? 0),
      ...(layer.mask === undefined ? {} : {mask: layerId(layer.mask)}),
    };
  });
  const tracks: MotionTrack[] = nested.value.tracks.map((track) => ({
    ...track, layer: layerId(track.layer),
  }));
  if (options.visible !== false) tracks.unshift({
    layer: options.id, property: "visible",
    keys: [{time: 0, value: true, curve: "step"}],
  });
  let markers: MotionAudioMarker[] = [];
  if (nested.value.markers?.length) {
    const byId = new Map(base.value.layers.map((layer) => [layer.id, layer]));
    let parentScale = 1;
    let parentOffset = 0;
    if (options.parent !== undefined) {
      const ancestry: MotionLayer[] = [];
      let id: string | undefined = options.parent;
      while (id !== undefined) {
        const layer = byId.get(id);
        if (layer === undefined) return error("PXMOTION2003",
          `Inline motion parent does not exist: ${id}`);
        ancestry.unshift(layer);
        id = layer.parent;
      }
      for (const layer of ancestry) {
        const layerScale = layer.timeScale ?? 1;
        parentOffset = parentOffset * layerScale + (layer.timeOffset ?? 0);
        parentScale *= layerScale;
      }
    }
    const scale = parentScale * speed;
    const offset = (parentOffset - at) * speed;
    if (!Number.isFinite(scale) || scale <= 0 || !Number.isFinite(offset))
      return error("PXMOTION2004",
        "Nested audio markers require a positive, finite parent-to-child time mapping");
    markers = nested.value.markers.map((marker) => ({
      ...marker, id: layerId(marker.id), time: (marker.time - offset) / scale,
    }));
  }
  return defineMotion({
    id: base.value.id, canvas: base.value.canvas, duration: base.value.duration,
    loop: base.value.loop,
    ...(base.value.scaleMode === undefined ? {} :
      {scaleMode: base.value.scaleMode}),
    layers: [...base.value.layers, group, ...layers],
    tracks: [...base.value.tracks, ...tracks],
    markers: [...(base.value.markers ?? []), ...markers]
      .sort((left, right) => left.time - right.time),
  });
}
